const LanguageContext = createContext({
  lang: 'en',
  setLang: () => {},
  t: (key) => key,
  translateIsland: (name) => name,
});

function readInitialLanguage() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === 'id' || saved === 'en') {
      return saved;
    }
  } catch {
    // Ignore storage errors in restricted contexts.
  }
  return 'en';
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(readInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
      // Ignore storage errors.
    }
  }, [lang]);

  const setLang = useCallback((next) => {
    setLangState(next === 'id' ? 'id' : 'en');
  }, []);

  const t = useCallback(
    (key, vars = {}) => {
      const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
      let template = dict[key] ?? TRANSLATIONS.en[key] ?? key;
      for (const [k, v] of Object.entries(vars)) {
        template = template.replaceAll(`{${k}}`, String(v ?? ''));
      }
      return template;
    },
    [lang]
  );

  const translateIsland = useCallback(
    (islandName) => {
      if (lang === 'id') {
        return ISLAND_LABELS_ID[islandName] || islandName;
      }
      return islandName;
    },
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang, t, translateIsland }),
    [lang, setLang, t, translateIsland]
  );

  return createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage() {
  return useContext(LanguageContext);
}
